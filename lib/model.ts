// Token Radar scoring model — ranks pre-token DeFi protocols by implied launch value.
//
// The model derives an implied value from four factors visible in the snapshot:
//   1. TVL base — a fraction of the protocol's TVL, the core capital base.
//   2. User growth — the 7-day TVL change, clamped and weighted.
//   3. Category boost — lending, DEX, bridge, staking, and derivatives categories
//      get a multiplier reflecting historical token-launch value.
//   4. Maturity — older protocols that have run longer without issuing a token
//      get a small boost, reflecting established product-market fit.
//
// No protocol name is ever hardcoded. Every row is scored by the same function.
// The constants are published in the dashboard and the board's model object.

/** One protocol as the sealed snapshot carries it: the ten fields the input defines. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The full snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** Tunable constants the dashboard states and the sandbox can override. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.25,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
};

/** Model version label, shown in the dashboard. */
export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the early radar includes. */
export const EARLY_ROWS = 160;

/** How many live-token protocols the Live token tab shows, by market cap. */
export const LIVE_ROWS = 24;

/** A farm step: the action text, its cost, and its time. */
export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

